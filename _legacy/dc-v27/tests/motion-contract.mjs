import assert from 'node:assert/strict';
import { readFileSync, statSync } from 'node:fs';
import { spawnSync } from 'node:child_process';

const html = readFileSync('Webinar Landing v3.dc.html', 'utf8');
const css = readFileSync('assets/css/landing.css', 'utf8');
const js = readFileSync('assets/js/motions.js', 'utf8');
const support = readFileSync('support.js', 'utf8');

const cssVersion = html.match(/landing\.css\?v=(\d+)/)?.[1];
const jsVersion = html.match(/motions\.js\?v=(\d+)/)?.[1];
const motionTypes = [...html.matchAll(/data-motion="([^"]+)"/g)].map((match) => match[1]);
const allowedMotionTypes = new Set(['rise', 'scale', 'top', 'left', 'right']);

assert(cssVersion && jsVersion, 'CSS e JS precisam de versão de cache.');
assert.equal(cssVersion, jsVersion, 'CSS e JS precisam usar a mesma versão de cache.');
assert(Number(cssVersion) >= 25, 'A correção de visibilidade precisa usar cache v25 ou superior.');
assert(/support\.js\?v=\d+" defer/.test(html), 'O runtime DC não pode bloquear o parser no head.');
assert(/scrollreveal\.min\.js\?v=[^"]+" defer/.test(html), 'ScrollReveal precisa carregar sem bloquear o parser.');
assert(/swiper-bundle\.min\.js\?v=[^"]+" defer/.test(html), 'Swiper precisa carregar sem bloquear o parser.');
assert(html.indexOf('react.production.min.js') < html.indexOf('support.js'), 'React local precisa carregar antes do runtime DC.');
assert(html.indexOf('react-dom.production.min.js') < html.indexOf('support.js'), 'ReactDOM local precisa carregar antes do runtime DC.');
assert(html.indexOf('scrollreveal.min.js') < html.indexOf('motions.js'), 'ScrollReveal precisa carregar antes de motions.js.');
assert(html.indexOf('swiper-bundle.min.js') < html.indexOf('motions.js'), 'Swiper precisa carregar antes de motions.js.');
assert(html.indexOf('support.js') < html.indexOf('scrollreveal.min.js'), 'O runtime essencial precisa vir antes das bibliotecas opcionais.');
assert.equal((html.match(/assets\/vendor\/swiper-bundle\.min\.(?:css|js)/g) || []).length, 2, 'Swiper precisa usar CSS e JS locais.');
assert(statSync('assets/vendor/react.production.min.js').size > 10_000, 'React local está ausente ou incompleto.');
assert(statSync('assets/vendor/react-dom.production.min.js').size > 100_000, 'ReactDOM local está ausente ou incompleto.');
assert(statSync('assets/vendor/scrollreveal.min.js').size > 10_000, 'ScrollReveal local está ausente ou incompleto.');
assert(statSync('assets/vendor/swiper-bundle.min.js').size > 100_000, 'Swiper local está ausente ou incompleto.');
assert(support.includes('loadReactUmd().then(() => {\n    hideRawTemplate();'), 'O template DC só pode ser ocultado depois que React estiver disponível.');
assert(!html.includes('<html class="motion-pending">'), 'O bloqueio de rolagem não pode existir estaticamente no HTML.');
assert(!css.includes('html.sr .sr-reveal{visibility:hidden}'), 'Conteúdo não pode depender do ScrollReveal para ficar visível.');
assert(css.includes('.motion-force-visible'), 'O sistema precisa possuir um estado fail-open.');
assert(js.includes('sr.sync()'), 'Conteúdo dinâmico do DC precisa ser sincronizado com ScrollReveal.');
assert(js.includes('outsideTemplate.length ? outsideTemplate'), 'A descoberta precisa aceitar render fora ou dentro de x-dc.');
assert(js.includes("!root.textContent.includes('{{')"), 'O template-fonte não pode ser confundido com a árvore renderizada.');
assert(js.includes("window.setTimeout(releaseMotionLock"), 'O loader precisa de destravamento independente.');
assert(!html.includes('data-loader-count'), 'O loader não deve exibir porcentagem ou contador.');
assert(!html.includes('data-loader-progress'), 'O loader não deve exibir barra de progresso.');
assert(html.includes('page-loader-curtain'), 'O loader precisa possuir uma transição de saída dedicada.');
assert(css.match(/prefers-reduced-motion[^}]*results-ribbon-track[^}]*animation\s*:\s*none/s), 'A faixa principal precisa parar no modo reduzido.');
assert(css.includes('@keyframes resultsRibbonFlow'), 'A faixa principal precisa de animação horizontal.');
assert(html.includes('method-card-rail'), 'Os módulos precisam declarar o rail horizontal mobile.');
assert(!html.includes('method-mechanism'), 'O método não deve duplicar as quatro decisões em duas sequências.');
assert.equal((html.match(/data-journey-step="0[1-7]"/g) || []).length, 7, 'A página precisa manter sete capítulos comerciais explícitos.');
assert(html.includes('class="curriculum-result"'), 'Cada bloco do método precisa concluir com uma decisão prática.');
assert(html.includes('hint-placeholder-count="4">\n          <div class="journey-card card u-062">'), 'O diagnóstico precisa espelhar as quatro decisões da operação.');
assert(html.includes('hero-question-deck'), 'O hero precisa mostrar o diagnóstico guiado por perguntas.');
assert.equal((html.match(/class="hero-visual hero-question-deck/g) || []).length, 1, 'O hero deve possuir um único deck de perguntas.');
assert.equal((html.match(/<article class="swiper-slide question-card/g) || []).length, 4, 'O deck precisa conter as quatro perguntas da operação.');
assert(html.includes('data-question-deck'), 'O deck precisa declarar seu container interativo.');
assert(!html.includes('course-module-list'), 'O hero não deve voltar ao formato de lista de módulos.');
assert(js.includes('new window.Swiper'), 'O deck precisa ser inicializado com Swiper.');
assert(js.includes("effect: reduceMotion ? 'slide' : 'cards'"), 'O deck precisa usar o efeito de cartões em camadas.');
assert(js.includes('questionSwiper.destroy(true, true)'), 'A instância do deck precisa ser destruída quando o root do DC mudar.');
assert(css.includes('.question-swiper:not(.swiper-initialized)'), 'O deck precisa continuar arrastável se o Swiper falhar.');
assert(!html.includes('class="hero-visual hero-offer-card'), 'O visual do hero não deve acumular a função de card de oferta.');
assert(!html.includes('deadlineIso'), 'O hero não deve manter configuração de cronômetro sem uso.');
assert(html.includes('data-conversion-dock aria-hidden="true"'), 'A barra de compra precisa começar contextual e fora da leitura do hero.');
assert(html.includes('class="journey-section journey-subsection final-decision"'), 'O capítulo 07 precisa fechar a decisão depois do FAQ.');
assert(js.includes("rail.dataset.railPosition"), 'Rails precisam expor progresso de navegação.');
assert(js.includes("conversionDock.classList.toggle('is-visible'"), 'A barra de compra precisa responder ao contexto de leitura.');
assert(css.includes('-webkit-line-clamp:unset!important'), 'O mobile precisa liberar textos críticos que antes eram truncados.');
assert(motionTypes.length >= 15, 'Os principais blocos precisam declarar data-motion explicitamente.');
assert(motionTypes.every((type) => allowedMotionTypes.has(type)), 'Existe um tipo data-motion não documentado.');
assert(!js.includes('new ScrollReveal'), 'ScrollReveal deve ser chamado sem new.');

const syntax = spawnSync(process.execPath, ['--check', 'assets/js/motions.js'], { encoding: 'utf8' });
assert.equal(syntax.status, 0, syntax.stderr || 'motions.js possui erro de sintaxe.');

console.log(`Motion contract OK: ${motionTypes.length} alvos, cache v${cssVersion}.`);
